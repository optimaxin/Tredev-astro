package com.tredevastro.app.data.auth

import android.app.Activity
import androidx.credentials.CredentialManager
import androidx.credentials.GetCredentialRequest
import com.google.android.libraries.identity.googleid.GetGoogleIdOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.FirebaseException
import com.google.firebase.auth.AuthCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.GoogleAuthProvider
import com.google.firebase.auth.PhoneAuthCredential
import com.google.firebase.auth.PhoneAuthOptions
import com.google.firebase.auth.PhoneAuthProvider
import kotlinx.coroutines.suspendCancellableCoroutine
import kotlinx.coroutines.tasks.await
import java.util.concurrent.TimeUnit
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

/** Firebase client half of sign-in. Every function ends in a Firebase ID token for AuthRepository.loginWithFirebase. */
object FirebaseSignIn {
    /** Returns the verificationId to pass to [verifyOtp]. (Auto-retrieved codes are ignored: the user types the OTP.) */
    suspend fun sendOtp(activity: Activity, phoneE164: String): String = suspendCancellableCoroutine { c ->
        val callbacks = object : PhoneAuthProvider.OnVerificationStateChangedCallbacks() {
            override fun onVerificationCompleted(credential: PhoneAuthCredential) {}
            override fun onVerificationFailed(e: FirebaseException) { if (c.isActive) c.resumeWithException(e) }
            override fun onCodeSent(id: String, token: PhoneAuthProvider.ForceResendingToken) { if (c.isActive) c.resume(id) }
        }
        PhoneAuthProvider.verifyPhoneNumber(
            PhoneAuthOptions.newBuilder(FirebaseAuth.getInstance())
                .setPhoneNumber(phoneE164).setTimeout(60L, TimeUnit.SECONDS)
                .setActivity(activity).setCallbacks(callbacks).build(),
        )
    }

    suspend fun verifyOtp(verificationId: String, code: String): String =
        idTokenFor(PhoneAuthProvider.getCredential(verificationId, code))

    suspend fun google(activity: Activity): String {
        // default_web_client_id is generated by the google-services plugin from google-services.json.
        val id = activity.resources.getIdentifier("default_web_client_id", "string", activity.packageName)
        if (id == 0) throw AuthException("Firebase isn't configured: add google-services.json (with Google sign-in enabled).")
        val option = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(activity.getString(id))
            .build()
        val result = CredentialManager.create(activity)
            .getCredential(activity, GetCredentialRequest.Builder().addCredentialOption(option).build())
        val google = GoogleIdTokenCredential.createFrom(result.credential.data)
        return idTokenFor(GoogleAuthProvider.getCredential(google.idToken, null))
    }

    private suspend fun idTokenFor(credential: AuthCredential): String {
        val user = FirebaseAuth.getInstance().signInWithCredential(credential).await().user
            ?: throw AuthException("Sign-in failed.")
        return user.getIdToken(false).await().token ?: throw AuthException("Sign-in failed.")
    }
}
